# 5. Offline-queue quarantine: PERMANENT_REJECT_STATUSES
# ---------------------------------------------------------------------------

def _response(status, *, json_body, text=""):
    resp = MagicMock()
    resp.status_code = status
    if json_body:
        resp.json.return_value = (
            {"status": "ok"} if status == 200 else {"error": "rejected"}
        )
    else:
        resp.json.side_effect = ValueError("response body is not JSON")
    resp.text = text
    return resp


@pytest.mark.parametrize("status", sorted(upload_photo.PERMANENT_REJECT_STATUSES))
@patch("upload_photo.requests.post")
def test_queue_app_reject_with_json_body_quarantines(mock_post, status, client_env):
    """An app-origin permanent reject (JSON body) moves the photo to
    rejected/ instead of wedging the queue, and the drain continues on to
    the next queued photo in the same pass."""
    queue = upload_photo.QUEUE_DIR
    queue.mkdir()
    poison = queue / "poison.jpg"
    poison.write_bytes(b"rejected-bytes")
    survivor = queue / "survivor.jpg"
    survivor.write_bytes(b"accepted-bytes")
    now = time.time()
    os.utime(poison, (now - 120, now - 120))  # older mtime drains first
    os.utime(survivor, (now - 60, now - 60))

    sent = []

    def fake_post(url, **kwargs):
        sent.append(kwargs["files"]["photo"][0])
        if len(sent) == 1:
            return _response(status, json_body=True, text='{"error": "rejected"}')
        return _response(200, json_body=True)

    mock_post.side_effect = fake_post

    upload_photo.process_queue()

    assert sent == ["poison.jpg", "survivor.jpg"]
    assert not poison.exists()
    assert (queue / "rejected" / "poison.jpg").read_bytes() == b"rejected-bytes"
    assert not survivor.exists()  # uploaded, not quarantined
    assert not (queue / "rejected" / "survivor.jpg").exists()


@patch("upload_photo.requests.post")
def test_queue_proxy_413_html_body_stays_queued_and_retries_later(mock_post, client_env):
    """The same 413 from an intermediary (HTML body — e.g. a default nginx
    1MB client_max_body_size) is transient: nothing is quarantined, the
    drain pauses, and a later drain retries the very same file."""
    queue = upload_photo.QUEUE_DIR
    queue.mkdir()
    first = queue / "first.jpg"
    first.write_bytes(b"first-bytes")
    second = queue / "second.jpg"
    second.write_bytes(b"second-bytes")
    now = time.time()
    os.utime(first, (now - 120, now - 120))
    os.utime(second, (now - 60, now - 60))

    mock_post.return_value = _response(
        413,
        json_body=False,
        text="<html><h1>413 Request Entity Too Large</h1><hr><center>nginx</center></html>",
    )
    upload_photo.process_queue()

    assert first.read_bytes() == b"first-bytes"  # kept, byte-for-byte
    assert second.exists()
    assert not (queue / "rejected").exists()  # nothing quarantined
    assert mock_post.call_count == 1  # drain paused at the first failure

    # Once the path stops rejecting, the SAME files drain normally.
    mock_post.reset_mock()
    mock_post.return_value = _response(200, json_body=True)
    upload_photo.process_queue()

    assert not first.exists()
    assert not second.exists()
    assert not (queue / "rejected").exists()
    assert mock_post.call_count == 2
