@patch("upload_photo.requests.post")
def test_sync_reoffers_photo_already_in_watcher_history(mock_post, client_env, tmp_path):
    """CLIENT-BEHAVIOR PIN for the startup-sync vs seeding race.

    android_watcher.sh seeds only photos OLDER than SEED_FRESH_MINUTES into
    uploaded_files.log; a fresher photo is uploaded by the first polls while
    the startup catch-up sync (sleep 30; upload_photo.py --sync) offers EVERY
    in-window photo to /reconcile. --sync never reads the watcher's history
    file, so when the first poll's upload is still in flight (slow cellular;
    30s request timeout) as /reconcile answers, the same photo IS uploaded a
    second time, concurrently — and on failure both processes can queue their
    own copy of it. Accepted design: the server dedups on original_hash and
    answers 200 for duplicates, so duplicate queue copies unlink on drain.
    This pins the client half of that contract: sync reconciliation is fully
    server-driven; no client-side record can suppress a re-offer.
    """
    camera = client_env
    fresh = camera / "fresh_meal.jpg"
    fresh.write_bytes(b"fresh-meal-bytes")
    fresh_hash = hashlib.md5(b"fresh-meal-bytes").hexdigest()
    # The watcher already uploaded this photo and recorded it in its history
    # file — a file upload_photo.py never opens.
    (tmp_path / "uploaded_files.log").write_text(f"{fresh}\n")

    offered, uploads = _drive_sync(mock_post, missing=[fresh_hash])

    assert offered == [fresh_hash]
    assert uploads == ["fresh_meal.jpg"]  # re-uploaded; the server dedups


