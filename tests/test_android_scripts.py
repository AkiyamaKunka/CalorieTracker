"""Cross-cutting Android client-script tests.

Covers: bash -n syntax gates for CI, the Termux:Boot script generated by
install_and_start.sh (including its pgrep double-start guard), installer
safety aborts (missing payload / truncated payload / missing config), the
--sync mtime lookback window, and offline-queue quarantine semantics for
PERMANENT_REJECT_STATUSES.

Bash pieces run under a sandboxed HOME with CALORIE_INSTALL_SRC pointing at
a tmp copy of the real payload, plus PATH shims for the Termux-only tools
(termux-wake-lock) and for anything with side effects (ps, nohup, pgrep,
sleep) so nothing real is killed or started on this machine. Python pieces
import android/upload_photo.py directly and mock requests.post.
"""

import ast
import hashlib
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path
from unittest.mock import MagicMock, patch

import pytest

BASH = shutil.which("bash")
REPO_ROOT = Path(__file__).resolve().parent.parent
ANDROID_DIR = REPO_ROOT / "android"
WATCHER = ANDROID_DIR / "android_watcher.sh"
INSTALLER = ANDROID_DIR / "install_and_start.sh"

sys.path.append(str(ANDROID_DIR))
import upload_photo

requires_bash = pytest.mark.skipif(BASH is None, reason="bash is not available")

# The installer's payload pre-flight is `python3 -c 'import ast...' <file>`;
# delegate -c to the real interpreter so a corrupt payload really aborts.
# Every other invocation (the --ping at the end) is logged and succeeds.
PYTHON3_SHIM = f"""#!/bin/sh
case "$1" in
  -c) exec "{sys.executable}" "$@" ;;
esac
echo "$@" >> "$HOME/python_calls.log"
exit 0
"""

# ps logs that it was consulted (the kill sweep's only observable) and lists
# no processes, so the sweep can never touch anything real on this machine.
PS_SHIM = """#!/bin/sh
echo "PS $@" >> "$HOME/ps_calls.log"
exit 0
"""

# nohup logs what it WOULD have launched instead of launching it, so the
# installer/boot script never actually start a watcher during tests.
NOHUP_SHIM = """#!/bin/sh
echo "NOHUP $@" >> "$HOME/nohup_calls.log"
exit 0
"""

# {code} is substituted per test: 0 simulates "a watcher already runs",
# 1 simulates "no watcher found".
PGREP_SHIM = """#!/bin/sh
echo "PGREP $@" >> "$HOME/pgrep_calls.log"
exit {code}
"""

NOOP_SHIM = "#!/bin/sh\nexit 0\n"


def _write_shim(path, body):
    path.write_text(body)
    path.chmod(0o755)


def _wait_for(predicate, timeout=10.0):
    deadline = time.time() + timeout
    while time.time() < deadline:
        if predicate():
            return True
        time.sleep(0.03)
    return False


def _installer_env(tmp_path, with_config=True):
    """Sandboxed HOME + tmp payload copy + side-effect-free PATH shims."""
    home = tmp_path / "home"
    src = tmp_path / "src"
    bin_dir = tmp_path / "bin"
    for directory in (home, src, bin_dir):
        directory.mkdir()
    shutil.copy(ANDROID_DIR / "upload_photo.py", src / "upload_photo.py")
    shutil.copy(WATCHER, src / "android_watcher.sh")
    _write_shim(bin_dir / "python3", PYTHON3_SHIM)
    _write_shim(bin_dir / "ps", PS_SHIM)
    _write_shim(bin_dir / "nohup", NOHUP_SHIM)
    _write_shim(bin_dir / "sleep", NOOP_SHIM)
    _write_shim(bin_dir / "termux-wake-lock", NOOP_SHIM)
    if with_config:
        (home / ".calorie_tracker_upload.json").write_text(
            '{"ANDROID_API_KEY": "k", "SERVER_URLS": ["http://example.test"]}'
        )
    env = dict(os.environ)
    env["HOME"] = str(home)
    env["PATH"] = str(bin_dir) + os.pathsep + env.get("PATH", "")
    env["CALORIE_INSTALL_SRC"] = str(src)
    env.pop("CALORIE_TRACKER_ANDROID_CONFIG", None)
    return env, home, src, bin_dir


def _run_installer(env):
    return subprocess.run(
        [BASH, str(INSTALLER)],
        env=env,
        capture_output=True,
        text=True,
        timeout=60,
    )


