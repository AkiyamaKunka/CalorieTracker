def _drive_sync(mock_post, missing=None):
    """Run sync_photos: /ping answers 200, /reconcile captures the offered
    hash list and reports `missing`, /upload records the uploaded filename."""
    offered = {}
    uploads = []

    def fake_post(url, **kwargs):
        resp = MagicMock()
        resp.status_code = 200
        if url.endswith("/reconcile"):
            offered["hashes"] = list(kwargs["json"]["hashes"])
            resp.json.return_value = {"missing_hashes": list(missing or [])}
        elif url.endswith("/upload"):
            uploads.append(kwargs["files"]["photo"][0])
            resp.json.return_value = {"status": "ok"}
        return resp

    mock_post.side_effect = fake_post
    upload_photo.sync_photos()
    return offered.get("hashes"), uploads


@patch("upload_photo.requests.post")
def test_sync_window_hashes_only_in_window_mtimes(mock_post, client_env, monkeypatch):
    """SYNC_LOOKBACK_DAYS=3 covers today plus the two previous calendar days:
    a 2-day-old photo is offered to /reconcile, a 4-day-old one is not."""
    monkeypatch.setattr(upload_photo, "SYNC_LOOKBACK_DAYS", 3)
    camera = client_env
    now = time.time()
    in_window = camera / "in_window.jpg"
    in_window.write_bytes(b"two-days-old-bytes")
    os.utime(in_window, (now - 2 * 86400, now - 2 * 86400))
    out_window = camera / "out_of_window.jpg"
    out_window.write_bytes(b"four-days-old-bytes")
    os.utime(out_window, (now - 4 * 86400, now - 4 * 86400))

    offered, uploads = _drive_sync(mock_post)

    assert offered == [hashlib.md5(b"two-days-old-bytes").hexdigest()]
    assert uploads == []  # server reported nothing missing


@patch("upload_photo.requests.post")
def test_sync_mtime_governs_over_filename_date(mock_post, client_env):
    """A photo NAMED like yesterday (IMG_YYYYMMDD_HHMMSS) whose mtime is 40
    days old is OUTSIDE the sync window: the mtime governs, not the filename.
    (The filename timestamp only dates the meal once a photo is uploaded.)"""
    camera = client_env
    now = time.time()
    yesterday = time.strftime("%Y%m%d", time.localtime(now - 86400))
    misnamed = camera / f"IMG_{yesterday}_120000.jpg"
    misnamed.write_bytes(b"stale-bytes-named-fresh")
    os.utime(misnamed, (now - 40 * 86400, now - 40 * 86400))
    control = camera / "control.jpg"
    control.write_bytes(b"control-bytes")  # mtime now: inside the window

    offered, uploads = _drive_sync(mock_post)

    assert offered == [hashlib.md5(b"control-bytes").hexdigest()]
    assert hashlib.md5(b"stale-bytes-named-fresh").hexdigest() not in offered
    assert uploads == []


