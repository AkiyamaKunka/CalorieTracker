@requires_bash
@pytest.mark.parametrize("missing", ["upload_photo.py", "android_watcher.sh"])
def test_missing_payload_aborts_before_kill_sweep(tmp_path, missing):
    """A missing payload file exits 1 BEFORE the kill sweep: ps is never even
    consulted, and the running watcher's state stays untouched."""
    env, home, src, bin_dir = _installer_env(tmp_path)
    (src / missing).unlink()
    pid_file = home / ".calorie_watcher.pid"
    pid_file.write_text("424242")

    result = _run_installer(env)

    assert result.returncode == 1
    assert f"{missing} not found" in result.stderr
    # The kill sweep's `ps` was never invoked, so nothing could be killed.
    assert not (home / "ps_calls.log").exists()
    assert pid_file.read_text() == "424242"
    assert not (home / "upload_photo.py").exists()
    assert not (home / "android_watcher.sh").exists()
    assert not (home / ".termux").exists()
    assert not (home / "nohup_calls.log").exists()


@requires_bash
def test_truncated_upload_photo_aborts_before_kill_sweep(tmp_path):
    """The real payload cut in half (a truncated adb push) must fail the ast
    pre-flight and abort BEFORE the kill sweep, leaving the watcher alone."""
    env, home, src, bin_dir = _installer_env(tmp_path)
    payload = (ANDROID_DIR / "upload_photo.py").read_bytes()
    truncated = payload[: len(payload) // 2]
    # Precondition: half the payload really is corrupt to the installer's
    # check (strict decode + ast.parse). If a refactor ever makes the halved
    # file parse cleanly, this fails loudly so the cut point can be adjusted.
    with pytest.raises((SyntaxError, UnicodeDecodeError)):
        ast.parse(truncated.decode())
    (src / "upload_photo.py").write_bytes(truncated)
    pid_file = home / ".calorie_watcher.pid"
    pid_file.write_text("424242")

    result = _run_installer(env)

    assert result.returncode == 1
    assert "syntax check" in result.stderr
    assert "left untouched" in result.stderr
    assert not (home / "ps_calls.log").exists()  # kill sweep never ran
    assert pid_file.read_text() == "424242"
    assert not (home / "upload_photo.py").exists()
    assert not (home / "android_watcher.sh").exists()
    assert not (home / "nohup_calls.log").exists()


