# ---------------------------------------------------------------------------
# 2. The Termux:Boot script the installer generates
# ---------------------------------------------------------------------------

@requires_bash
def test_installer_generates_pgrep_guarded_boot_script(tmp_path):
    """A successful install writes an executable, syntactically valid boot
    script whose pgrep guard starts the watcher only when none is running."""
    env, home, src, bin_dir = _installer_env(tmp_path)

    result = _run_installer(env)

    assert result.returncode == 0, result.stderr
    assert "Installed Termux:Boot auto-start script." in result.stdout
    boot = home / ".termux" / "boot" / "start-calorie-tracker.sh"
    assert boot.is_file()
    assert os.access(boot, os.X_OK)
    syntax = subprocess.run(
        [BASH, "-n", str(boot)], capture_output=True, text=True, timeout=30
    )
    assert syntax.returncode == 0, syntax.stderr

    # The installer itself launched the watcher (via the nohup shim, so
    # nothing really started). The launch is backgrounded with &, so wait
    # for the shim's log. Then clear it for the boot-script runs below.
    nohup_log = home / "nohup_calls.log"
    assert _wait_for(
        lambda: nohup_log.exists() and "android_watcher.sh" in nohup_log.read_text()
    )
    nohup_log.unlink()

    # pgrep exit 0 = a watcher is already running: the boot script must NOT
    # launch a second one, and still exits cleanly.
    _write_shim(bin_dir / "pgrep", PGREP_SHIM.format(code=0))
    blocked = subprocess.run(
        [BASH, str(boot)], env=env, capture_output=True, text=True, timeout=30
    )
    assert blocked.returncode == 0
    time.sleep(0.3)  # a wrongly-backgrounded nohup would have logged by now
    assert not nohup_log.exists()
    # The guard really consulted pgrep with the watcher pattern.
    assert "-f android_watcher.sh" in (home / "pgrep_calls.log").read_text()

    # pgrep exit 1 = no watcher found: the boot script launches one.
    _write_shim(bin_dir / "pgrep", PGREP_SHIM.format(code=1))
    started = subprocess.run(
        [BASH, str(boot)], env=env, capture_output=True, text=True, timeout=30
    )
    assert started.returncode == 0
    assert _wait_for(
        lambda: nohup_log.exists() and "android_watcher.sh" in nohup_log.read_text()
    )
    assert f"bash {home}/android_watcher.sh" in nohup_log.read_text()


